"function handleControl(line){"
" if(line.startsWith('CTL autodownload')){"
"  if(cbAdl.checked){download()}"
" } else if(line.startsWith('STATUS ')){"
"  refreshStatus();"
" }"
"}"

"function appendFrame(line){"
" if(!gotFirstKey){live.textContent='';gotFirstKey=true}"
" if(line.startsWith('KEY ')){"
"  let body=line.slice(4);"
"  if(body.endsWith('\\n'))body=body.slice(0,-1);"    // drop wire terminator
"  if(!body)return;"
"  if(body==='\\\\n'){live.append('\\n');return;}"    // real Enter -> newline
"  if(body.startsWith('[')&&body.endsWith(']')){"
"   const sp=document.createElement('span');sp.className='s';sp.textContent=body;live.append(sp);"
"  } else {"
"   live.append(body);"
"  }"
" } else if(line.startsWith('EVT ')){"
"  const rest=line.slice(4).trim();"
"  const sp=document.createElement('span');sp.className='e';"
"  const m=rest.match(/^ENUM_RETRY\\s+(\\d+)\\s+(\\d+)$/);"
"  if(m){sp.textContent='(hub retry '+m[1]+'/'+m[2]+')\\n';}"
"  else if(rest==='ENUM_OK'){sp.textContent='(keyboard enumerated)\\n';}"
"  else if(rest==='ENUM_FAIL'){sp.textContent='(hub gave up — re-seat keyboard)\\n';}"
"  else if(rest==='PC_CONNECT'){sp.textContent='(PC connected — keystrokes will reach Windows)\\n';}"
"  else if(rest==='PC_DISCONNECT'){sp.textContent='(PC disconnected)\\n';}"
"  else {sp.textContent='('+rest+')\\n';}"
"  live.append(sp);"
"  refreshStatus();"
" }"
" while(live.childNodes.length>4000)live.removeChild(live.firstChild);"
" live.scrollTop=live.scrollHeight;"
"}"

"function onWsData(txt){"
" for(const line of txt.split('\\n')){"
"  if(!line)continue;"
"  if(line.charCodeAt(0)===0x1e){handleControl(line.slice(1));continue}"
"  appendFrame(line+'\\n');"
" }"
"}"

"function connect(){"
" try{if(ws&&(ws.readyState===0||ws.readyState===1))return;}catch(_){}"
" ws=new WebSocket('ws://'+location.host+'/ws');"
" ws.onopen=()=>setPill($('p_ws'),'ok','WebSocket: connected');"
" ws.onmessage=e=>onWsData(e.data);"
" ws.onclose=()=>{setPill($('p_ws'),'warn','WebSocket: disconnected');setTimeout(connect,2000)};"
" ws.onerror=()=>setPill($('p_ws'),'warn','WebSocket: error');"
"}"
"connect();"
// Mobile browsers throttle timers when the tab is backgrounded, so a WS
// dropped while the phone slept can stay dead until user refreshes. Force a
// reconnect the moment the tab becomes visible again.
"document.addEventListener('visibilitychange',()=>{if(document.visibilityState==='visible'){connect();refreshStatus();}});"

"$('b_rec_start').onclick =()=>fetch('/rec/start', {method:'POST'}).then(refreshStatus);"
"$('b_rec_stop').onclick  =()=>fetch('/rec/stop',  {method:'POST'}).then(refreshStatus);"
"$('b_live_start').onclick=()=>fetch('/live/start',{method:'POST'}).then(refreshStatus);"
"$('b_live_stop').onclick =()=>fetch('/live/stop', {method:'POST'}).then(refreshStatus);"
"cbAdl.onchange=()=>fetch('/autodl?v='+(cbAdl.checked?1:0),{method:'POST'}).then(refreshStatus);"
"$('sel_led').onchange=()=>fetch('/led?m='+$('sel_led').value,{method:'POST'}).then(refreshStatus);"
"$('sel_layout').onchange=()=>fetch('/layout?v='+$('sel_layout').value,{method:'POST'}).then(refreshStatus);"

"function download(){"
" const a=document.createElement('a');"
" a.href='/log/download?t='+Date.now();"
" a.download='keylog-'+new Date().toISOString().slice(0,19).replaceAll(':','-')+'.txt';"
" document.body.appendChild(a);a.click();a.remove();"
"}"
"function del(){"
" if(!confirm('Delete all recorded log data?'))return;"
" fetch('/log/delete',{method:'POST'}).then(refreshStatus);"
"}"
"function clr(){live.textContent='';gotFirstKey=false;live.textContent='[cleared — waiting for keys…]'}"

"refreshStatus();setInterval(refreshStatus,3000);"
"</script></body></html>";

